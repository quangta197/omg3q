/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require("fs");
const path = require("path");
const { createClient } = require("@supabase/supabase-js");

const TABLES = [
  "servers",
  "nations",
  "accounts",
  "account_images",
  "account_heroes",
  "contact_requests",
  "site_settings",
  "site_visits",
];

function loadEnv(file) {
  if (!fs.existsSync(file)) {
    return;
  }

  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#") || !trimmed.includes("=")) {
      continue;
    }

    const index = trimmed.indexOf("=");
    const key = trimmed.slice(0, index).trim();
    let value = trimmed.slice(index + 1).trim();

    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }

    process.env[key] = value;
  }
}

function timestamp() {
  return new Date().toISOString().replace(/[-:]/g, "").replace(/\.\d+Z$/, "Z");
}

function sqlIdentifier(value) {
  return `"${String(value).replace(/"/g, '""')}"`;
}

function sqlValue(value) {
  if (value === null || value === undefined) {
    return "NULL";
  }

  if (typeof value === "number") {
    return Number.isFinite(value) ? String(value) : "NULL";
  }

  if (typeof value === "boolean") {
    return value ? "true" : "false";
  }

  const stringValue =
    typeof value === "object" ? JSON.stringify(value) : String(value);

  return `'${stringValue.replace(/'/g, "''")}'`;
}

async function fetchAllRows(supabase, table) {
  const rows = [];
  const pageSize = 1000;

  for (let from = 0; ; from += pageSize) {
    const to = from + pageSize - 1;
    const { data, error } = await supabase.from(table).select("*").range(from, to);

    if (error) {
      if (
        error.code === "42P01" ||
        error.message.toLowerCase().includes("does not exist") ||
        error.message.toLowerCase().includes("could not find the table")
      ) {
        return { rows, missing: true };
      }

      throw error;
    }

    rows.push(...(data || []));

    if (!data || data.length < pageSize) {
      return { rows, missing: false };
    }
  }
}

async function listStorageObjects(storage, prefix = "") {
  const objects = [];
  const pageSize = 1000;

  for (let offset = 0; ; offset += pageSize) {
    const { data, error } = await storage.list(prefix, {
      limit: pageSize,
      offset,
      sortBy: { column: "name", order: "asc" },
    });

    if (error) {
      throw error;
    }

    const rows = data || [];

    for (const item of rows) {
      const itemPath = prefix ? `${prefix}/${item.name}` : item.name;

      if (item.id === null || item.metadata === null) {
        objects.push(...(await listStorageObjects(storage, itemPath)));
      } else {
        objects.push({
          path: itemPath,
          id: item.id,
          size: Number(item.metadata?.size || 0),
          mimetype: item.metadata?.mimetype || item.metadata?.contentType || null,
          created_at: item.created_at || null,
          updated_at: item.updated_at || null,
        });
      }
    }

    if (rows.length < pageSize) {
      return objects;
    }
  }
}

async function main() {
  loadEnv(path.join(process.cwd(), ".env.local"));

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const serviceRoleKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

  if (!url || !serviceRoleKey) {
    throw new Error("Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY.");
  }

  const backupDir = path.join(process.cwd(), "..", "backups", `supabase-${timestamp()}`);
  const dataDir = path.join(backupDir, "data");
  fs.mkdirSync(dataDir, { recursive: true });

  const supabase = createClient(url, serviceRoleKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
  const manifest = {
    generatedAt: new Date().toISOString(),
    supabaseUrl: url,
    tables: {},
    storage: null,
  };
  const insertSql = [];

  insertSql.push("-- Supabase public data dump generated by scripts/dump-supabase-data.js");
  insertSql.push(`-- Generated at ${manifest.generatedAt}`);
  insertSql.push("BEGIN;");

  for (const table of TABLES) {
    const { rows, missing } = await fetchAllRows(supabase, table);
    manifest.tables[table] = { rows: rows.length, missing };

    fs.writeFileSync(
      path.join(dataDir, `${table}.json`),
      JSON.stringify(rows, null, 2) + "\n"
    );

    if (missing || rows.length === 0) {
      continue;
    }

    for (const row of rows) {
      const columns = Object.keys(row);
      insertSql.push(
        `INSERT INTO public.${sqlIdentifier(table)} (${columns
          .map(sqlIdentifier)
          .join(", ")}) VALUES (${columns.map((column) => sqlValue(row[column])).join(", ")});`
      );
    }
  }

  insertSql.push("COMMIT;");
  fs.writeFileSync(path.join(backupDir, "data.sql"), insertSql.join("\n") + "\n");

  const schemaPath = path.join(process.cwd(), "..", "database", "schema.sql");
  if (fs.existsSync(schemaPath)) {
    fs.copyFileSync(schemaPath, path.join(backupDir, "schema.sql"));
  }

  const bucket = process.env.SUPABASE_STORAGE_BUCKET || "account-images";

  try {
    const storageObjects = await listStorageObjects(supabase.storage.from(bucket));
    manifest.storage = {
      bucket,
      objects: storageObjects.length,
      totalBytes: storageObjects.reduce((sum, item) => sum + item.size, 0),
    };
    fs.writeFileSync(
      path.join(backupDir, "storage-manifest.json"),
      JSON.stringify(storageObjects, null, 2) + "\n"
    );
  } catch (error) {
    manifest.storage = {
      bucket,
      error: error.message || String(error),
    };
  }

  fs.writeFileSync(
    path.join(backupDir, "manifest.json"),
    JSON.stringify(manifest, null, 2) + "\n"
  );

  console.log(JSON.stringify({ backupDir, manifest }, null, 2));
}

main().catch((error) => {
  console.error(error.stack || error.message || error);
  process.exit(1);
});
